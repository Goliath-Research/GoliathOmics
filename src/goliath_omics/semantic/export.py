"""Export omics semantic catalog JSON and PostgreSQL composite row types."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Optional, Sequence

from goliath_app.semantic.export import _pg_type_for_field, _schema_id, content_hash_for, export_row_types_sql
from goliath_app.semantic.spec import SemanticEntitySpec, SemanticRequestSpec

from goliath_omics.semantic.catalog import SEMANTIC_CATALOG, SEMANTIC_REQUESTS


def _row_type_name(entity: SemanticEntitySpec) -> str:
    return f"{entity.namespace}_{entity.code}_row".replace(".", "_")


def _camel_to_snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def _result_row_type_name(req: SemanticRequestSpec) -> str:
    model_name = req.result_row_model.__name__
    if model_name.endswith("Row"):
        model_name = model_name[:-3]
    return f"{req.namespace}_{_camel_to_snake(model_name)}_row".replace(".", "_")


def request_row_type(req: SemanticRequestSpec, entity: SemanticEntitySpec) -> str:
    if req.result_row_model is entity.row_model:
        return f"portal.{_row_type_name(entity)}"
    return f"portal.{_result_row_type_name(req)}"


def _align_omics_row_type_sql(sql: str) -> str:
    """Match PostgreSQL list/view types: bigint sample_count, numeric age and inv quantities."""
    return (
        sql.replace("sample_count integer", "sample_count bigint")
        .replace(
            "ARRAY['integer', 'text', 'text', 'integer', 'integer']",
            "ARRAY['integer', 'text', 'text', 'integer', 'bigint']",
        )
        .replace("age double precision", "age numeric")
        .replace(
            "ARRAY['integer', 'integer', 'integer', 'integer', 'text', 'double precision', 'double precision']",
            "ARRAY['integer', 'integer', 'integer', 'integer', 'text', 'numeric', 'double precision']",
        )
        .replace("qty_on_hand double precision", "qty_on_hand numeric")
        .replace("unit_cost double precision", "unit_cost numeric")
    )


def _pg_type_for_schema_field(field_schema: dict[str, Any]) -> str:
    any_of = field_schema.get("anyOf")
    if isinstance(any_of, list):
        variants = [variant for variant in any_of if variant.get("type") != "null"]
        if len(variants) == 1:
            field_schema = variants[0]
    if field_schema.get("format") == "date":
        return "date"
    return _pg_type_for_field(field_schema)


def _row_type_sql_block(type_name: str, model_schema: dict[str, Any]) -> list[str]:
    props = model_schema.get("properties", {})
    field_parts: list[str] = []
    for name, field_schema in props.items():
        pg_t = _pg_type_for_schema_field(field_schema)
        field_parts.append(f"  {name} {pg_t}")
    fields_sql = ",\n".join(field_parts)
    return [
        "DO $$",
        "BEGIN",
        "  IF NOT EXISTS (",
        "    SELECT 1 FROM pg_type t",
        "    JOIN pg_namespace n ON n.oid = t.typnamespace",
        f"    WHERE n.nspname = 'portal' AND t.typname = '{type_name}'",
        "  ) THEN",
        f"    CREATE TYPE portal.{type_name} AS (",
        f"{fields_sql}",
        "    );",
        "  END IF;",
        "END $$;",
        "",
    ]


def export_omics_row_types_sql() -> str:
    header = (
        "/*\n"
        "  Composite row types for omics semantic requests (generated by goliath-omics-semantic-export).\n"
        "  Do not edit by hand; run goliath-omics-semantic-export -o database/schema/09_portal_semantic_row_types.sql\n"
        "*/\n\n"
    )
    lines: list[str] = []
    emitted: set[str] = set()
    for entity in SEMANTIC_CATALOG:
        type_name = _row_type_name(entity)
        if type_name in emitted:
            continue
        emitted.add(type_name)
        model_schema = entity.row_model.model_json_schema(mode="serialization")
        lines.extend(_row_type_sql_block(type_name, model_schema))
    catalog_entities = {e.code: e for e in SEMANTIC_CATALOG}
    for req in SEMANTIC_REQUESTS:
        entity = catalog_entities[req.entity_code]
        if req.result_row_model is entity.row_model:
            continue
        type_name = _result_row_type_name(req)
        if type_name in emitted:
            continue
        emitted.add(type_name)
        model_schema = req.result_row_model.model_json_schema(mode="serialization")
        lines.extend(_row_type_sql_block(type_name, model_schema))
    body = _align_omics_row_type_sql("\n".join(lines))
    return header + body + "\n"


def export_catalog_document() -> dict[str, Any]:
    entities: dict[str, Any] = {}
    for entity in SEMANTIC_CATALOG:
        row_schema = entity.row_model.model_json_schema(mode="serialization")
        entity_hash = content_hash_for(
            {
                "namespace": entity.namespace,
                "code": entity.code,
                "schema_version": entity.schema_version,
                "meta_class_id": entity.meta_class_id,
                "meta_class_name": entity.meta_class_name,
                "row_schema": row_schema,
                "attributes": [a.__dict__ for a in entity.attributes],
            }
        )
        entities[f"{entity.namespace}.{entity.code}"] = {
            "namespace": entity.namespace,
            "code": entity.code,
            "display_name": entity.display_name,
            "description": entity.description,
            "schema_id": _schema_id(entity),
            "schema_version": entity.schema_version,
            "content_hash": entity_hash,
            "storage_relation": entity.storage_relation,
            "meta_class_id": entity.meta_class_id,
            "meta_class_name": entity.meta_class_name,
            "catalog_type_name": None,
            "row_type": f"portal.{_row_type_name(entity)}",
            "row_schema": row_schema,
            "attributes": [
                {
                    "code": a.code,
                    "column_name": a.column_name,
                    "json_type": a.json_type,
                    "role": a.role,
                    "filterable_ops": list(a.filterable_ops),
                }
                for a in entity.attributes
            ],
        }

    catalog_entities = {e.code: e for e in SEMANTIC_CATALOG}

    def entity_by_code(code: str) -> SemanticEntitySpec:
        entity = catalog_entities.get(code)
        if entity is None:
            raise KeyError(f"unknown entity code {code}")
        return entity

    requests: dict[str, Any] = {}
    for req in SEMANTIC_REQUESTS:
        entity = entity_by_code(req.entity_code)
        params_schema = req.params_model.model_json_schema(mode="serialization")
        result_schema = req.result_row_model.model_json_schema(mode="serialization")
        filter_payload = (
            req.filter_template.model_dump(mode="json") if req.filter_template is not None else None
        )
        req_hash = content_hash_for(
            {
                "request_code": req.request_code,
                "version": req.version,
                "params_schema": params_schema,
                "result_schema": result_schema,
                "filter_template": filter_payload,
            }
        )
        requests[req.request_code] = {
            "request_code": req.request_code,
            "version": req.version,
            "namespace": req.namespace,
            "entity_code": req.entity_code,
            "target_kind": req.target_kind,
            "target_name": req.target_name,
            "row_type": request_row_type(req, entity),
            "params_schema": params_schema,
            "result_schema": result_schema,
            "filter_template": filter_payload,
            "schema_id": f"goliath.semantic/{req.namespace}/{req.request_code}/{req.version}",
            "content_hash": req_hash,
            "required_permission": req.required_permission,
            "max_rows": req.max_rows,
            "base_namespace": req.base_namespace,
        }

    return {
        "entities": entities,
        "requests": requests,
        "row_types_sql": export_omics_row_types_sql(),
    }


def _check_mode(catalog_path: Path, row_types_path: Optional[Path]) -> int:
    with catalog_path.open(encoding="utf-8") as fh:
        committed = json.load(fh)
    live = export_catalog_document()
    if committed != {k: v for k, v in live.items() if k != "row_types_sql"}:
        print(
            "semantic export drift: regenerate schemas/semantic/catalog.json",
            file=sys.stderr,
        )
        return 1
    if row_types_path is not None:
        live_sql = live["row_types_sql"]
        if row_types_path.read_text(encoding="utf-8") != live_sql:
            print(
                "semantic export drift: regenerate database/schema/09_portal_semantic_row_types.sql",
                file=sys.stderr,
            )
            return 1
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Export GoliathOmics semantic catalog")
    parser.add_argument(
        "--check",
        metavar="PATH",
        help="Compare export to committed catalog.json",
    )
    parser.add_argument(
        "--row-types",
        metavar="PATH",
        help="Path to portal_semantic_row_types.sql for --check",
    )
    parser.add_argument("-o", "--output", metavar="PATH", help="Write row types SQL")
    parser.add_argument(
        "--catalog",
        metavar="PATH",
        help="Write catalog.json (entities + requests, without row_types_sql)",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.check:
        row_path = Path(args.row_types) if args.row_types else None
        return _check_mode(Path(args.check), row_path)

    document = export_catalog_document()
    if args.catalog:
        catalog_doc = {k: v for k, v in document.items() if k != "row_types_sql"}
        Path(args.catalog).write_text(
            json.dumps(catalog_doc, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
    if args.output:
        Path(args.output).write_text(document["row_types_sql"], encoding="utf-8")
    elif not args.catalog:
        sys.stdout.write(json.dumps(document, indent=2, sort_keys=True) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
