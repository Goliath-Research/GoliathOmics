#!/usr/bin/env bash
# Write /work/goliath/env/worker.env for one architecture.
# Image names come from platform_matrix.env. Secrets are copied only when
# already present in the environment; this script never prints them.

set -euo pipefail

usage() {
  cat <<'EOF'
Usage: scripts/write_worker_env.sh [options]

Options:
  --root PATH     Goliath root (default: /work/goliath)
  --arch KEY      aarch64 or amd64 (default: detect)
  --api-base URL  WORKER_API_BASE to record (default: $WORKER_API_BASE)
  --capability NAME
  -h, --help
EOF
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=detect_platform.sh
source "$SCRIPT_DIR/detect_platform.sh"

ROOT="${GOLIATH_ROOT:-/work/goliath}"
ARCH=""
API_BASE="${WORKER_API_BASE:-${METHYL_API_BASE:-}}"
CAPABILITY="${WORKER_CAPABILITY:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --root) ROOT="${2:-}"; shift 2 ;;
    --arch) ARCH="${2:-}"; shift 2 ;;
    --api-base) API_BASE="${2:-}"; shift 2 ;;
    --capability) CAPABILITY="${2:-}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

info() { echo "[INFO] $*"; }

ARCH="${ARCH:-$(platform_arch_key "$(detect_uname_arch)")}"
VENV="$ROOT/venv-$ARCH"
mkdir -p "$ROOT/env"
ENV_FILE="$ROOT/env/worker.env"

PATH_VALUE="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
if [[ -d "$VENV" ]]; then
  PATH_VALUE="$(expand_worker_path "$VENV")"
fi

# shellcheck disable=SC1090
source "${PLATFORM_MATRIX_FILE:-$SCRIPT_DIR/platform_matrix.env}"
pb_var="PARABRICKS_IMAGE_${ARCH}"
mg_var="METHYLGRAPHER_IMAGE_${ARCH}"
PB_IMAGE="${!pb_var:-}"
MG_IMAGE="${!mg_var:-}"

umask 077
{
  echo "# Generated by write_worker_env.sh — do not commit."
  echo "PATH=${PATH_VALUE}"
  echo "GOLIATH_ROOT=${ROOT}"
  echo "GOLIATH_ARCH=${ARCH}"
  if [[ -n "${GOLIATH_ENV:-}" ]]; then
    echo "GOLIATH_ENV=${GOLIATH_ENV}"
  fi
  if [[ -n "$API_BASE" ]]; then
    echo "WORKER_API_BASE=${API_BASE}"
  fi
  if [[ -n "$CAPABILITY" ]]; then
    echo "WORKER_CAPABILITY=${CAPABILITY}"
  fi
  if [[ -n "$PB_IMAGE" ]]; then
    echo "METHYL_PARABRICKS_IMAGE=${PB_IMAGE}"
  fi
  if [[ -n "$MG_IMAGE" ]]; then
    echo "METHYL_METHYLGRAPHER_IMAGE=${MG_IMAGE}"
  fi
  extractor_env="$ROOT/env/methyl-extractor-${ARCH}.env"
  if [[ -f "$extractor_env" ]]; then
    echo "# MethylExtractor variables live in ${extractor_env}"
  fi
} >"$ENV_FILE"
chmod 600 "$ENV_FILE" 2>/dev/null || true
info "Wrote $ENV_FILE"
