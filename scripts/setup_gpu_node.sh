#!/usr/bin/env bash
# Record the Parabricks image for this arch and optionally docker-pull it.
# Sources platform_matrix.env. Does not embed registry credentials.

set -euo pipefail

usage() {
  cat <<'EOF'
Usage: scripts/setup_gpu_node.sh [options]

Options:
  --root PATH          Goliath root (default: /work/goliath)
  --arch KEY           aarch64 or amd64 (default: detect)
  --pull               docker pull the resolved Parabricks image
  --skip-docker-pull   Do not pull (default)
  --require-gpu        Fail when nvidia-smi is missing
  -h, --help
EOF
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=detect_platform.sh
source "$SCRIPT_DIR/detect_platform.sh"

ROOT="${GOLIATH_ROOT:-/work/goliath}"
ARCH=""
PULL=0
REQUIRE_GPU=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --root) ROOT="${2:-}"; shift 2 ;;
    --arch) ARCH="${2:-}"; shift 2 ;;
    --pull|--pull-parabricks) PULL=1; shift ;;
    --skip-docker-pull) PULL=0; shift ;;
    --require-gpu|--gpu) REQUIRE_GPU=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

info() { echo "[INFO] $*"; }
die() { echo "[ERROR] $*" >&2; exit 1; }

ARCH="${ARCH:-$(platform_arch_key "$(detect_uname_arch)")}"
if [[ "$REQUIRE_GPU" -eq 1 ]]; then
  command -v nvidia-smi >/dev/null 2>&1 || die "nvidia-smi not found"
  nvidia-smi >/dev/null
fi

# Honor --arch even when this host is a different architecture.
# shellcheck disable=SC1090
source "${PLATFORM_MATRIX_FILE:-$SCRIPT_DIR/platform_matrix.env}"
image_var="PARABRICKS_IMAGE_${ARCH}"
IMAGE="${!image_var:-}"
mkdir -p "$ROOT/env"
{
  echo "# Generated by setup_gpu_node.sh"
  echo "GOLIATH_ARCH=${ARCH}"
  if [[ -n "$IMAGE" ]]; then
    echo "METHYL_PARABRICKS_IMAGE=${IMAGE}"
    echo "PARABRICKS_IMAGE=${IMAGE}"
  fi
} >"$ROOT/env/parabricks.env"
info "Wrote $ROOT/env/parabricks.env"

if [[ "$PULL" -eq 1 ]]; then
  [[ -n "$IMAGE" ]] || die "No Parabricks image resolved for $ARCH"
  command -v docker >/dev/null 2>&1 || die "docker is required for --pull"
  info "docker pull $IMAGE"
  docker pull "$IMAGE"
fi
