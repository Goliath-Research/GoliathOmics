#!/bin/bash
# Extract a GoliathExtractor pipeline tarball and configure PATH + HDF5_PLUGIN_PATH.

set -euo pipefail

usage() {
  cat <<'EOF'
Usage: scripts/install_methyl_extractor_tarball.sh [options]

Options:
  --tarball PATH        Path to goliath-extractor-linux-<arch>.tar.gz (required)
  --dest DIR            Local install dir (default: $GOLIATH_LOCAL_ROOT/goliath-extractor-<arch>,
                        GOLIATH_LOCAL_ROOT=/opt/goliath; never under /work)
  --arch KEY            aarch64 or amd64 (default: detect from tarball name or machine)
  --goliath-root PATH GoliathOmics root for env file (default: /work/goliath)
  --user-env            Append source line to ~/.bashrc (default: yes)
  --no-user-env         Skip ~/.bashrc update
  -h, --help            Show this help

After install, open a new shell or run:
  source /work/goliath/env/goliath-extractor-<arch>.env

Production workers get the same variables from scripts/write_worker_env.sh during promote.
EOF
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=detect_platform.sh
source "$SCRIPT_DIR/detect_platform.sh"
# shellcheck source=rollouts_hook.sh
source "$SCRIPT_DIR/rollouts_hook.sh"
# shellcheck source=methyl_extractor_local.sh
source "$SCRIPT_DIR/methyl_extractor_local.sh"

TARBALL=""
DEST=""
ARCH=""
GOLIATH_ROOT="${GOLIATH_ROOT:-/work/goliath}"
USER_ENV=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --tarball) TARBALL="${2:-}"; shift 2 ;;
    --dest) DEST="${2:-}"; shift 2 ;;
    --arch) ARCH="${2:-}"; shift 2 ;;
    --goliath-root) GOLIATH_ROOT="${2:-}"; shift 2 ;;
    --user-env) USER_ENV=1; shift ;;
    --no-user-env) USER_ENV=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

info() { echo "[INFO] $*"; }
die() { echo "[ERROR] $*" >&2; exit 1; }

[[ -n "$TARBALL" ]] || die "--tarball is required"
[[ -f "$TARBALL" ]] || die "Tarball not found: $TARBALL"

rollouts_begin goliath-extractor "goliath-extractor $(hostname -s 2>/dev/null || hostname)"

basename_tar="$(basename "$TARBALL")"
if [[ -z "$ARCH" ]]; then
  if [[ "$basename_tar" =~ goliath-extractor-linux-(aarch64|amd64) ]]; then
    ARCH="${BASH_REMATCH[1]}"
  elif [[ "$basename_tar" =~ methyl-extractor-linux-(aarch64|amd64) ]]; then
    ARCH="${BASH_REMATCH[1]}"
  else
    ARCH="$(platform_arch_key "$(detect_uname_arch)")"
  fi
fi

# Native binaries never go onto the shared volume (it ignores exec bits and
# cannot read back extracted files). --dest overrides the local dir; a dest
# under GOLIATH_WORK_MOUNT falls back to /tmp.
if [[ -n "$DEST" ]]; then
  export GOLIATH_EXTRACTOR_HOME="$DEST"
fi
ENV_FILE="$GOLIATH_ROOT/env/goliath-extractor-${ARCH}.env"
MARKER="# GoliathOmics GoliathExtractor environment ($ARCH)"

install_methyl_extractor_local "$TARBALL" "$ARCH" || die "GoliathExtractor install failed"
DEST="$GOLIATH_EXTRACTOR_HOME"
ME_BIN="$(_mel_bin_in_home "$DEST" || true)"
[[ -n "$ME_BIN" ]] || ME_BIN="$DEST/bin/goliath-extractor"

mkdir -p "$GOLIATH_ROOT/env"
cat >"$ENV_FILE" <<EOF
# Generated by install_methyl_extractor_tarball.sh — do not edit by hand.
export GOLIATH_EXTRACTOR_HOME="$DEST"
export GOLIATH_EXTRACTOR_BIN="$ME_BIN"
export METHYL_EXTRACTOR_HOME="$DEST"
export METHYL_EXTRACTOR_BIN="$ME_BIN"
export HDF5_PLUGIN_PATH="$DEST/lib/hdf5_zstd_plugin"
export PATH="$DEST/bin:\$PATH"
EOF
info "Wrote $ENV_FILE"

if [[ "$USER_ENV" -eq 1 ]]; then
  bashrc="${HOME}/.bashrc"
  if [[ -f "$bashrc" ]] && ! grep -qF "$MARKER" "$bashrc" 2>/dev/null; then
    {
      echo ""
      echo "$MARKER"
      echo "[ -f \"$ENV_FILE\" ] && source \"$ENV_FILE\""
    } >>"$bashrc"
    info "Appended source line to $bashrc"
  fi
fi

info "GoliathExtractor: $ME_BIN"
info "HDF5_PLUGIN_PATH=$DEST/lib/hdf5_zstd_plugin"
info "Install OK. Run: source \"$ENV_FILE\""
rollouts_set_message "goliath-extractor arch=${ARCH} dest=${DEST}"
