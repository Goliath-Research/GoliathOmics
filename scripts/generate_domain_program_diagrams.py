def _try_load_platform_mermaid() -> ModuleType | None:
    """Locate GoliathApp's canonical ``domain.mermaid`` module if available."""
    candidates: list[Path] = []
    env_gw = os.environ.get("GOLIATH_GATEWAY_WORKFLOW_ENGINE")
    if env_gw:
        candidates.append(Path(env_gw) / "domain" / "mermaid.py")
    candidates.append(REPO_ROOT.parent / "GoliathApp" / "workflow_engine" / "domain" / "mermaid.py")
    for entry in list(sys.path):
        if entry:
            candidates.append(Path(entry) / "domain" / "mermaid.py")

    local_domain_dir = (REPO_ROOT / "workflow_engine" / "domain").resolve()
    for candidate in candidates:
        try:
            resolved = candidate.resolve()
        except OSError:
            continue
        if not resolved.is_file():
            continue
        if resolved.parent == local_domain_dir:
            continue
        spec = importlib.util.spec_from_file_location("goliathapp_domain_mermaid", resolved)
        if spec is None or spec.loader is None:
            continue
        mod = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = mod
        spec.loader.exec_module(mod)
        return mod
    return None


