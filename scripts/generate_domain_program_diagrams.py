#!/usr/bin/env python3
"""Generate Mermaid flowchart documentation for every GoliathOmics DomainProgram fixture.

Delegates to GoliathApp's generic ``domain.mermaid`` module when installed
(via ``goliath-gateway``, ``GOLIATH_GATEWAY_WORKFLOW_ENGINE``, or a sibling
``../GoliathApp/workflow_engine`` checkout) and falls back to an identical
stdlib-only renderer when running in a standalone docs environment (such as
the lightweight MkDocs CI job).

Usage (from repository root):

    # Regenerate docs/workflows/*.md
    python3 scripts/generate_domain_program_diagrams.py

    # Verify committed docs match the current fixtures (CI drift check)
    python3 scripts/generate_domain_program_diagrams.py --check

    # Export standalone .mmd files (for course lessons or external embeds)
    python3 scripts/generate_domain_program_diagrams.py --emit-mmd-dir /tmp/goliath-omics-mmd
"""

